### ステップ4：3年生は「1級3種目以上」と、その先の資格へ

3年生になったら、まずは1級を3種目以上そろえることを目標にしましょう。すでに達成している人は、次のような「その先」の資格にも挑戦できます。

- [財務諸表分析検定](/subjects/zaimu-shohyo-bunseki)：簿記で「作る側」だった決算書を、「読む側」として分析する検定です
