## まず知っておきたい、全商検定の3つのポイント

### 1. 検定の内容は、授業とつながっている

全商検定は、商業高校の授業で習う内容がそのまま出題されます。授業で習ったタイミングで受けると、復習がそのまま検定対策になるので効率がいいです。

### 2. 3級 → 2級 → 1級の順にステップアップ

どの検定も、いきなり1級を目指すより、3級・2級で基礎を固めてから1級に進むほうが近道です。特に簿記は、3級の仕訳があいまいなまま進むと、2級・1級で必ずつまずきます。

### 3. 1級を3種目以上とると、卒業時に表彰される

全国商業高等学校協会では、**全商検定の1級に3種目以上合格した高校生を、卒業のときに表彰**しています。がんばった証になるだけでなく、進学や就職のときに「在学中に努力し続けた」ことを伝える材料にもなります。

どの検定を何種目と数えるかは、学校の先生に確認しておくと安心です。

## おすすめの順番と、その理由

### ステップ1：電卓実務検定と簿記実務検定（1年生）

最初におすすめなのが、[電卓実務検定](/subjects/dentaku-jitsumu)と[簿記実務検定](/subjects/zensho-boki)です。

電卓を速く正確に打てるようになると、簿記の計算問題で時間が足りなくなることが減ります。電卓で身につけた力が、そのまま簿記の得点につながるので、この2つはセットで進めるのがおすすめです。

簿記は、多くの商業高校で最初に習う科目で、全商検定の中心になる検定です。**「なぜその仕訳になるのか」を理解しながら**進めると、2級・1級に上がったときにも崩れにくくなります。

### ステップ2：情報処理検定とビジネス文書実務検定（1〜2年生）

次は、パソコンを使う検定です。

- [情報処理検定（ビジネス情報）](/subjects/business-joho)：表計算ソフトの関数やグラフ、情報の知識
- [情報処理検定（プログラミング）](/subjects/programming)：プログラムの考え方と、処理の流れの読み取り
- [ビジネス文書実務検定](/subjects/bunsho-sakusei)：速く正確に入力する力と、ビジネス文書の書き方

どれも就職してから毎日のように使う力です。特に表計算は、簿記の考え方とも相性がいいので、簿記の次に取り組むと理解しやすくなります。

### ステップ3：英語検定と商業経済検定で、1級の数を増やす（2年生）

[英語検定](/subjects/zensho-eiken)や[商業経済検定](/subjects/shogyo-keizai)は、ほかの検定と勉強の中身が重なりにくいぶん、コツコツ進めた分だけ結果につながりやすい検定です。

「簿記と情報処理で1級がとれたから、あと1つ1級がほしい」というときの、3種目めの候補にもなります。英語は、単語と長文を毎日少しずつ続けることが合格への近道です。

