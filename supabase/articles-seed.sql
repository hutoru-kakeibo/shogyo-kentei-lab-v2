## 3年間の合格ロードマップ（例）

学校の予定や得意・不得意によって変わりますが、たとえば次のような進め方があります。

- **1年生**：電卓実務検定と簿記実務検定の3級・2級。まずは「検定に合格する」経験を積む
- **2年生**：簿記実務検定1級に挑戦しながら、情報処理検定・ビジネス文書実務検定・英語検定で2級・1級を目指す
- **3年生**：1級を3種目以上そろえる。余裕があれば、財務諸表分析検定や日商簿記検定にも挑戦する

## 順番を決めるときの3つのコツ

### 1. 検定日から逆算して、同じ時期に受ける数を増やしすぎない

検定日が近い時期に何種目も重なると、どれも中途半端になりがちです。検定日から逆算して、「今回はこの検定に集中する」と決めておきましょう。各検定の実施時期は、[対応検定一覧](/subjects)からまとめて確認できます。

### 2. 苦手な検定を、後回しにしすぎない

苦手な検定ほど、3年生の直前にまとめて対策しようとすると苦しくなります。1年生・2年生のうちに3級・2級だけでもとっておくと、3年生で1級を目指すときの負担がぐっと軽くなります。

### 3. 「なぜ落ちたか」を毎回ふり返る

不合格だったときは、点数だけでなく「どの問題で、なぜ間違えたか」を書き出しておきましょう。次の検定までに直すべきところがはっきりすると、同じ失点をくり返さなくなります。

## 推薦入試・就職で、検定を活かすには

全商検定の1級は、進学や就職のときにアピールできる実績になります。大学や短期大学の推薦入試・総合型選抜では、学校によって、全商検定の取得を出願の条件にしていたり、評価の材料にしていたりすることがあります。

志望校が決まっていなくても、次の2つを意識しておくと、選べる進路が広がります。

- 行きたい学校の募集要項で、どの検定の何級が求められているかを早めに確認する
- 3年生の夏までに、アピールしたい検定の結果をそろえておく

就職でも、検定は履歴書の資格欄に書ける、目に見える実績です。特に簿記と情報処理は、事務の仕事でそのまま役立ちます。

