## 違い1：全商英検は「商業高校の授業」とつながっている

全商英検は、商業高校生のために作られた検定です。そのため、学校の英語の授業で扱う内容がそのまま出題され、ビジネスの場面を扱った英文がよく登場します。

これは大きな利点です。**授業の復習がそのまま検定対策になる**ので、部活や他の検定と並行していても、勉強時間を分け合わずに進められます。

一方の英検は、小学生から社会人までが受ける全国共通の検定です。学校の授業とは別に、その級の範囲に合わせた対策が必要になります。

## 違い2：問われる力の範囲が違う

全商英検は、リスニングと読解が中心です。面接形式のスピーキング試験はありません。「聞き取る力」と「読み取る力」を、決まった出題形式の中で確実に発揮できるかが問われます。

