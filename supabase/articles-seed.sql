## 結局、どっちを受けるべき？

迷ったときの考え方を3つに整理します。

### パターン1：まずは学校の検定を確実に取りたい

**全商英検を優先**しましょう。授業の内容がそのまま対策になるので、いちばん少ない負担で結果につながります。学校でまとめて受験するため、申し込みの手間も少なくて済みます。

### パターン2：大学進学で英語力をアピールしたい

**志望校の募集要項を先に確認**してください。英検が指定されているなら英検の対策が必要ですし、全商検定が評価されるなら全商英検を伸ばすほうが効率的です。どちらとも書かれていない場合は、取りやすい全商英検から始めて、余力で英検に挑戦する形が現実的です。

### パターン3：どちらも受けたい

**全商英検を先に受けるのがおすすめ**です。リスニングと読解は両方の検定に共通する土台なので、全商英検の対策でその力を固めてから、英検で足りない「書く・話す」を追加していくと、勉強が二度手間になりません。

## よくある質問

### 全商英検1級は、英検の何級くらいですか？

公式な換算表はありません。出題される内容も、問われる力の範囲も違うため、「全商1級＝英検◯級」と言い切ることはできないのです。

ただし、全商英検1級の読解問題を時間内に解ける力がある人は、英検の読解でも戦えることが多いです。差が出やすいのは英作文と面接なので、英検に挑戦するならその2つを重点的に準備しましょう。

### 全商英検の合格点は何点ですか？

1級は70点以上、2級と3級は60点以上が合格の基準です。リスニングと読解のどちらかが極端に苦手だと届きにくいので、模擬試験のあとは合計点だけでなく、**どちらで落としたか**を必ず確認してください。

### 全商英検はいつ実施されますか？

年2回の実施です。学校を通じた団体受験が基本なので、申し込みの締め切りは学校の案内にしたがってください。最新の日程と実施要項は全国商業高等学校協会の発表を確認しましょう。

